// ─── buildHtml — static mode flag ────────────────────────

describe('buildHtml — staticMode', () => {
  const rows = [
    { key: 'hello', translations: { en: 'Hello', pl: 'Cześć' } },
    { key: 'bye', translations: { en: 'Goodbye', pl: 'Do widzenia' } },
  ];
  const languages = ['en', 'pl'];
  const validationResult = { issues: [], refLang: 'en', totalKeys: 2 };
  const statsResult = {
    refLang: 'en',
    refKeyCount: 2,
    languages: ['en', 'pl'],
    langStats: [
      { lang: 'en', total: 2, translated: 2, missing: 0, coverage: 100, topMissing: [] },
      { lang: 'pl', total: 2, translated: 2, missing: 0, coverage: 100, topMissing: [] },
    ],
    overallCoverage: 100,
  };

  it('returns HTML string with STATIC_MODE = false by default', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult);
    assert.ok(html.includes('STATIC_MODE = false'), 'should contain STATIC_MODE = false');
  });

  it('returns HTML string with STATIC_MODE = true when staticMode=true', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(html.includes('STATIC_MODE = true'), 'should contain STATIC_MODE = true');
  });

  it('embeds all translation data in static mode', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(html.includes('Hello'), 'should contain English value');
    assert.ok(html.includes('Cześć'), 'should contain Polish value');
    assert.ok(html.includes('hello'), 'should contain key "hello"');
    assert.ok(html.includes('bye'), 'should contain key "bye"');
  });

  it('hides save bar in static mode', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(html.includes('id="saveBar"'), 'saveBar element should exist');
    // In static mode the save bar div should have display:none
    assert.ok(html.includes('style="display:none"'), 'save bar should be hidden with display:none');
  });

  it('includes static footer in static mode', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(
      html.includes('Static preview generated by'),
      'should contain static footer text'
    );
    assert.ok(
      html.includes('translation-toolkit'),
      'footer should mention translation-toolkit'
    );
  });

  it('does NOT include static footer in server mode', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, false);
    assert.ok(
      !html.includes('Static preview generated by'),
      'server mode should NOT have static footer'
    );
  });

  it('includes client-side CSV parser in static mode', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(
      html.includes('parseCsvString') || html.includes('csvToData') || html.includes('clientDiff'),
      'should contain client-side diff functions'
    );
  });

  it('produces a valid HTML document', () => {
    const html = buildHtml(rows, languages, FIXTURES, validationResult, statsResult, true);
    assert.ok(html.startsWith('<!DOCTYPE html>') || html.startsWith('<html'), 'should start with DOCTYPE or html tag');
    assert.ok(html.includes('</html>'), 'should end with closing html tag');
  });
});


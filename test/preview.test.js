// ─── CLI: --static flag ──────────────────────────────────

describe('CLI --static flag', () => {
  it('generates default translation-preview/index.html', () => {
    const cwd = TMP;
    // Clean up any previous output
    const defaultDir = path.join(cwd, 'translation-preview');
    if (fs.existsSync(defaultDir)) fs.rmSync(defaultDir, { recursive: true });
    const defaultOutput = path.join(defaultDir, 'index.html');

    execFileSync(process.execPath, [CLI, 'preview', '--dir', FIXTURES, '--static'], {
      cwd,
      timeout: 10000,
    });

    assert.ok(fs.existsSync(defaultOutput), 'should create translation-preview/index.html');

    const content = fs.readFileSync(defaultOutput, 'utf-8');
    assert.ok(content.includes('STATIC_MODE = true'), 'default output should have STATIC_MODE = true');
  });

  it('respects -o / --output flag', () => {
    const customPath = path.join(TMP, 'custom-output.html');
    if (fs.existsSync(customPath)) fs.unlinkSync(customPath);

    execFileSync(process.execPath, [CLI, 'preview', '--dir', FIXTURES, '--static', '-o', customPath], {
      timeout: 10000,
    });

    assert.ok(fs.existsSync(customPath), 'should create file at custom output path');
  });

  it('uses short flags -s and -d', () => {
    const outPath = path.join(TMP, 'short-flags.html');
    if (fs.existsSync(outPath)) fs.unlinkSync(outPath);

    execFileSync(process.execPath, [CLI, 'preview', '-d', FIXTURES, '-s', '-o', outPath], {
      timeout: 10000,
    });

    assert.ok(fs.existsSync(outPath), 'should work with short flags -d -s -o');
  });

  it('rejects --watch + --static combination', () => {
    assert.throws(
      () => {
        execFileSync(process.execPath, [CLI, 'preview', '--dir', FIXTURES, '--static', '--watch'], {
          timeout: 10000,
          stdio: 'pipe',
        });
      },
      (err) => {
        return err.status !== 0;
      },
      'should exit with non-zero status when --watch and --static are combined'
    );
  });

  it('rejects --static when no .po files are found', () => {
    const emptyDir = path.join(TMP, 'empty-dir');
    fs.mkdirSync(emptyDir, { recursive: true });

    assert.throws(
      () => {
        execFileSync(process.execPath, [CLI, 'preview', '--dir', emptyDir, '--static'], {
          timeout: 10000,
          stdio: 'pipe',
        });
      },
      (err) => {
        return err.status !== 0;
      },
      'should exit with non-zero status when no .po files found'
    );
  });
});

